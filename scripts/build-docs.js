// מייצר את VOICE_GUIDE.md ו-AUDIO_FILES.md ישירות מתוך lib/game.js,
// כך שהטקסטים בקבצים תמיד זהים למה שהמשחק משמיע.
// שימוש: node scripts/build-docs.js
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOMS, MESSAGES } from '../lib/game.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// הטקסט המלא שמושמע לכל מזהה: בחידה הראשונה בחדר - תיאור החדר + החידה
function fullPuzzleText(room, idx) {
  const p = room.puzzles[idx];
  return idx === 0 ? `${room.intro} ${p.text}` : p.text;
}

const VOICE = `# מדריך הקריינות - אחוזת בלקווד

## סגנון כללי
- **קול:** גבר בוגר, מדויק, עם נימה רגועה וקצת מסתורית. לא דרמטי מדי ולא מתנשא.
- **טון:** שקט ומכובד. המתקשר הוא חוקר, והקריין מדבר אליו בכבוד ובעניין.
- **קצב:** מדיטטיבי. הפסקה קצרה אחרי נקודה, הפסקה ארוכה יותר אחרי משפט שמסמן רמז.
- **רגש:** מתח עדין בתיאורי החדרים, בהירות מלאה בהוראות המשחק, חום וגאווה בסיום.
- **ביטוי:** ברור לכל קהל. לא להשתמש בסלנג ולא בביטויים לועזיים.
- **מספרים:** להקריא בצורה מלאה ("שתיים עשרה", "אלף שמונה מאות חמישים ושבע").
- **הקלטה:** 8 קילוהרץ, מונו, 16 ביט, רמת שקט נמוכה ללא נשימות חזקות.

## כללי ביצוע חשובים
1. להקריא את הטקסט כפי שהוא, בלי לשנות מילים. כל שינוי משנה את משמעות החידה.
2. במשפטי הוראה ("הקישו", "סולמית") - להאט מעט ולהשמיע את המילה בבירור.
3. בתיאורי חדרים - להוסיף מעט מתח, אך לא להפחיד.
4. הקלטה אחת לכל קובץ. שם הקובץ זהה למזהה שברשימה (לדוגמה: \`r1_p1.wav\`).

---

`;

let body = '';
body += '## הודעות המערכת\n\n';
for (const [key, text] of Object.entries(MESSAGES)) {
  body += `### ${key}.wav\n\n> ${text}\n\n`;
}
body += '---\n\n';
for (const room of ROOMS) {
  body += `## חדר ${room.id}: ${room.name}\n\n`;
  room.puzzles.forEach((p, idx) => {
    body += `### ${p.id}.wav (${p.type === 'choice' ? 'בחירה' : 'הקשת ספרות'})\n\n`;
    body += `> ${fullPuzzleText(room, idx)}\n\n`;
    body += `*רמז להקראה בלחיצה על 99:* ${p.hint}\n\n`;
  });
}

writeFileSync(join(root, 'VOICE_GUIDE.md'), VOICE + body, 'utf8');

// רשימת קבצי השמע
const EFFECTS = [
  ['door_creak', 'חריקת דלת', 'כניסה לחדר הכניסה וכניסה לכל חדר חדש (כ-1.8 שניות)'],
  ['chime', 'פעמון הצלחה', 'לאחר תשובה נכונה (כ-1.4 שניות)'],
  ['error_buzz', 'זמזם שגיאה', 'לאחר תשובה שגויה (כ-0.7 שניות)'],
  ['tick', 'תקתוק שעון', 'בחדר השעונים (כ-0.25 שניות)'],
  ['heartbeat', 'פעימות לב', 'לפני חידה מסתורית בחדר המרתף (כ-1.6 שניות)'],
  ['wind', 'רוח בחלון', 'בגלריה ובגן החורף (כ-3 שניות)'],
  ['hatch_open', 'פתיחת דלת נסתרת', 'בפתיחת המעבר הסודי מחדר המוזיקה (כ-1.2 שניות)'],
  ['fanfare', 'פנפרה', 'בסיום חדר (כ-2.4 שניות)'],
  ['final_bell', 'פעמון סיום', 'בפתיחת הכספת (כ-4 שניות)'],
  ['ambient_drone', 'מוזיקת רקע', 'רקע לולאתי לשלוחה הראשית (כ-12 שניות, להגדיר לולאה)'],
];

let audio = `# רשימת קובצי השמע

כל הקבצים נמצאים בתיקייה \`audio/\` של הפרויקט. יש להעלות אותם לשלוחת השמע בימות המשיח, תחת שם הקובץ המדויק.
מצב הקראה \`AUDIO_MODE=tts\` (ברירת מחדל) מקריא את הטקסטים בעזרת מנוע הדיבור של ימות המשיח ואינו דורש העלאת קבצים.
מצב \`AUDIO_MODE=file\` דורש העלאה של כל הקבצים שברשימה.

## אפקטים קוליים (נוצרים אוטומטית)
יוצרים בעזרת \`node scripts/generate-effects.js\`.

**חשוב:** האפקטים אינם מחוברים אוטומטית לזרימת השיחה בגרסה זו. ימות המשיח מנגנת בכל תגובה קריינה אחת בלבד. להלן השימוש המוצע, שניתן לממש בעזרת שלוחת השמעה נפרדת או במסך הזרמה נוסף.

| שם הקובץ | תיאור | שימוש מוצע |
|---|---|---|
${EFFECTS.map(([f, d, u]) => `| \`${f}.wav\` | ${d} | ${u} |`).join('\n')}

## קריינות הודעות מערכת
| שם הקובץ | מיקום השימוש |
|---|---|
${Object.keys(MESSAGES).map(k => `| \`${k}.wav\` | הודעת מערכת: ${k} |`).join('\n')}

## קריינות חידות
| שם הקובץ | חדר | סוג |
|---|---|---|
${ROOMS.flatMap(r => r.puzzles.map(p => `| \`${p.id}.wav\` | ${r.id}. ${r.name} | ${p.type === 'choice' ? 'בחירה' : 'הקשת ספרות'} |`)).join('\n')}

## הערות התקנה
- כל הקבצים מועלים לשלוחה שבה מוגדר ה-type=api (או לתיקייה שמוגדרת ב-api_dir).
- שמות הקבצים רגישים לאותיות גדולות וקטנות. יש להעלות בדיוק את השמות שברשימה.
- לאחר העלאה, להשמיע כל קובץ בטלפון אחד לפחות כדי לוודא שהשמע תקין.
`;
writeFileSync(join(root, 'AUDIO_FILES.md'), audio, 'utf8');
console.log('נוצרו VOICE_GUIDE.md ו-AUDIO_FILES.md');
