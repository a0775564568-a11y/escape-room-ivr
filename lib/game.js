export function roomById(id) { return ROOMS.find(r => r.id === Number(id)); }

// כל מזהי השמע שהמשחק משתמש בהם, עם הטקסט המלא לכל אחד.
export function allNarrationKeys() {
  const out = [];
  out.push({ key: 'prologue', text: MESSAGES.prologue, section: 'פתיחה' });
  for (const [k, v] of Object.entries(MESSAGES)) {
    if (k === 'prologue') continue;
    out.push({ key: k, text: v, section: 'הודעות מערכת' });
  }
  for (const r of ROOMS) {
    out.push({ key: `r${r.id}_intro`, text: r.intro, section: `חדר ${r.id}: ${r.name}` });
    for (const p of r.puzzles) {
      out.push({ key: p.id, text: p.text, section: `חדר ${r.id}: ${r.name}` });
      out.push({ key: `${p.id}_ok`, text: p.ok, section: `חדר ${r.id}: ${r.name}` });
    }
    if (r.outro) out.push({ key: `r${r.id}_outro`, text: r.outro, section: `חדר ${r.id}: ${r.name}` });
  }
  out.push({ key: 'epilogue', text: MESSAGES.epilogue, section: 'סיום' });
  return out;
}
