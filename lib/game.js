// כל מזהי השמע שהמשחק משתמש בהם, לצורך יצירת רשימת הקבצים.
export function allNarrationKeys() {
  const out = [];
  for (const [k, v] of Object.entries(MESSAGES)) out.push({ key: k, text: v });
  for (const r of ROOMS) {
    for (const p of r.puzzles) out.push({ key: p.id, text: p.text, room: r.name });
  }
  return out;
}
